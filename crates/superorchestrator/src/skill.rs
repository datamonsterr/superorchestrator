//! The shipped `superorchestrator` skill (SPEC 19.1), generated from the current accounts
//! and choices so it can be regenerated whenever they change.

use std::fmt::Write as _;

use so_core::{AccountFile, Choice};

/// Marker line in every generated `SKILL.md`. `uninstall` and re-generation only touch
/// files that carry it.
pub const MARKER: &str = "<!-- superorchestrator:managed -->";

/// Renders the skill's `SKILL.md`.
pub fn render_skill(accounts: &[AccountFile], choices: &[Choice]) -> String {
    let mut out = String::new();
    out.push_str(
        "---\nname: superorchestrator\ndescription: Delegate coding work to other agents across \
         harnesses and accounts (claude, codex, opencode, agy) through the superorchestrator MCP \
         server. Use it to route, spawn, wait on, message and review subagent runs.\n---\n",
    );
    let _ = writeln!(out, "{MARKER}\n");
    out.push_str("# superorchestrator\n\n");
    out.push_str(
        "Use the `superorchestrator` MCP tools to hand work to subagents that run on other \
         harnesses and accounts. This file is generated by `superorchestrator install`; do not \
         edit it by hand.\n\n",
    );

    out.push_str("## Accounts\n\n");
    if accounts.is_empty() {
        out.push_str("No accounts are configured. Run `superorchestrator account add`.\n\n");
    } else {
        for a in accounts {
            let _ = writeln!(
                out,
                "- `{}`: {}, cap {}{}",
                a.name,
                a.harness.as_str(),
                a.cap,
                if a.enabled { "" } else { " (disabled)" }
            );
        }
        out.push('\n');
    }

    out.push_str("## Choices\n\n");
    let enabled: Vec<&Choice> = choices.iter().filter(|c| c.enabled).collect();
    if enabled.is_empty() {
        out.push_str("No choices are enabled. Edit `choices` in `config.toml`.\n\n");
    } else {
        for c in enabled {
            let _ = write!(out, "- `{}`: {} / {}", c.id, c.harness.as_str(), c.model);
            if let Some(e) = &c.effort {
                let _ = write!(out, " ({e})");
            }
            if !c.roles.is_empty() {
                let _ = write!(out, ", roles: {}", c.roles.join(", "));
            }
            if !c.description.is_empty() {
                let _ = write!(out, ". {}", c.description);
            }
            out.push('\n');
        }
        out.push('\n');
    }

    out.push_str(BODY);
    out
}

const BODY: &str = "\
Call `list_harnesses` for the live picture: signed-in state, headroom and active runs per \
account.

## route or spawn_agent

- `route` previews which choice and account the router would pick. It runs nothing. Use it \
when you want to see or sanity-check a decision first.
- `spawn_agent` starts a run. With `harness: auto` (the default) the router picks. Pass \
`account`, `model` or `effort` only when you have a reason to override it. Set `wait: true` to \
block until the run finishes; otherwise it returns a run id.

## Writing a task brief

The subagent starts with no context. Put in the `prompt`:

1. The goal in one or two sentences.
2. Acceptance criteria: observable checks that say the work is done (tests that must pass, \
commands that must succeed).
3. Out of scope: what it must not touch or decide.
4. Pointers: files, docs and constraints it needs.

Use `output_schema` when you need a structured final result, and `review: true` when you want to \
inspect the work before it counts as done.

## Waiting, messaging and reviewing

- `wait_agent(runs, timeout)` returns when a listed run finishes, asks a question or reports \
progress, or when the timeout ends.
- `get_run` shows state, recent events, the final result and the worktree.
- `send_message(run, text)` talks to a running run; sent to a finished run it resumes the \
session.
- `read_messages` returns unread messages for you. Answer a child's question with \
`send_message`.
- A run in `pending_review` waits for `accept_run` or `reject_run`.
- `cancel_agent` stops a run and its subtree.

## If you are a subagent

You run with a run id and must never wait for a person.

- `report_progress(step, status)` at each step.
- `ask_parent(question, options?)` for decisions and blockers. It blocks until answered.
- `read_messages` for messages from your parent.
- Finish with a final result, matching the schema if one was given.
- Call `spawn_agent` only when your depth is below 2.

## Checking on things

Run `superorchestrator status` for accounts, headroom and the supervisor, and \
`superorchestrator runs list` for runs.
";

#[cfg(test)]
mod tests {
    use super::*;
    use so_core::Harness;

    fn choice(id: &str, enabled: bool) -> Choice {
        Choice {
            id: id.into(),
            harness: Harness::Codex,
            model: "gpt".into(),
            effort: Some("high".into()),
            roles: vec!["code".into()],
            description: "fast".into(),
            enabled,
        }
    }

    #[test]
    fn lists_accounts_and_enabled_choices_with_marker() {
        let mut off = AccountFile::new("claude-b", Harness::Claude, "~/b", "claude").unwrap();
        off.enabled = false;
        let accounts = [
            AccountFile::new("codex-a", Harness::Codex, "~/a", "codex").unwrap(),
            off,
        ];
        let s = render_skill(&accounts, &[choice("c1", true), choice("c2", false)]);
        assert!(s.starts_with("---\nname: superorchestrator\n"));
        assert!(s.contains(MARKER));
        assert!(s.contains("- `codex-a`: codex, cap"));
        assert!(s.contains("(disabled)"));
        assert!(s.contains("`c1`: codex / gpt (high), roles: code. fast"));
        assert!(!s.contains("`c2`"));
        assert!(s.contains("superorchestrator status"));
    }

    #[test]
    fn empty_state_still_renders() {
        let s = render_skill(&[], &[]);
        assert!(s.contains("No accounts are configured"));
        assert!(s.contains("No choices are enabled"));
    }
}
