    out.push('\n');
    out.push_str(WORKFLOW);
    out.push_str(
        "Accounts, choices: `list_harnesses`. Agents: `list_agents`, then `agent: \"<name>\"`.\n\n",
    );
    out.push_str(BODY);
    out
