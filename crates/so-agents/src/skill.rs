//! The shipped `superorchestrator` skill (SPEC 19.1), generated from the current accounts,
//! choices and agents, and regenerated whenever they change.
//!
//! It lives in this crate so the CLI and the web API can both refresh it.

use std::fmt::Write as _;
use std::path::{Path, PathBuf};
use std::sync::atomic::{AtomicU64, Ordering};

use so_core::{AccountFile, Choice, Config, Paths};

use crate::{AgentDef, discover::discover_user};

/// Directory name of the skill under `~/.claude/skills` and `~/.agents/skills`.
pub const NAME: &str = "superorchestrator";

const FRONT_MATTER: &str = "---\nname: superorchestrator\ndescription: Delegate coding work to other agents across \
harnesses and accounts (claude, codex, opencode, agy) through the superorchestrator MCP \
server. Use it to route, spawn, wait on, message and review subagent runs.\n---\n";

/// Environment variable that disables [`refresh`].
pub const SKIP_ENV: &str = "SUPERORCHESTRATOR_SKIP_SKILL_REFRESH";

/// Longest agent description kept in the skill, in characters.
const DESCRIPTION_MAX: usize = 160;

/// Marker line in every generated `SKILL.md`. `uninstall` and re-generation only touch
/// files that carry it.
pub const MARKER: &str = "<!-- superorchestrator:managed -->";

/// Renders the skill's `SKILL.md`.
pub fn render_skill(accounts: &[AccountFile], choices: &[Choice], agents: &[AgentDef]) -> String {
    let mut out = String::new();
    out.push_str(FRONT_MATTER);
    let _ = writeln!(out, "{MARKER}\n");
    out.push_str("# superorchestrator\n\n");
    out.push_str(
        "Use the `superorchestrator` MCP tools to hand work to subagents that run on other \
         harnesses and accounts. This file is generated by `superorchestrator install`; do not \
         edit it by hand.\n\n",
    );

    out.push_str("## Accounts\n\n");
    if accounts.is_empty() {
        out.push_str("No accounts are configured. Run `superorchestrator account add`.\n\n");
    } else {
        for a in accounts {
            let _ = writeln!(
                out,
                "- `{}`: {}, cap {}{}",
                a.name,
                a.harness.as_str(),
                a.cap,
                if a.enabled { "" } else { " (disabled)" }
            );
        }
        out.push('\n');
    }

    out.push_str("## Choices\n\n");
    let enabled: Vec<&Choice> = choices.iter().filter(|c| c.enabled).collect();
    if enabled.is_empty() {
        out.push_str("No choices are enabled. Edit `choices` in `config.toml`.\n\n");
    } else {
        for c in enabled {
            let _ = write!(out, "- `{}`: {} / {}", c.id, c.harness.as_str(), c.model);
            if let Some(e) = &c.effort {
                let _ = write!(out, " ({e})");
            }
            if !c.roles.is_empty() {
                let _ = write!(out, ", roles: {}", c.roles.join(", "));
            }
            if !c.description.is_empty() {
                let _ = write!(out, ". {}", c.description);
            }
            out.push('\n');
        }
        out.push('\n');
    }

    out.push_str("## Agents\n\n");
    if agents.is_empty() {
        out.push_str(
            "No custom agents are defined. `superorchestrator agent create` makes one.\n\n",
        );
    } else {
        out.push_str("Pass `agent: \"<name>\"` to `spawn_agent` to use one.\n\n");
        for a in agents {
            let _ = write!(out, "- `{}` ({})", a.name, a.harness.as_str());
            let d = one_line(&a.description, DESCRIPTION_MAX);
            if !d.is_empty() {
                let _ = write!(out, ": {d}");
            }
            out.push('\n');
        }
        out.push('\n');
    }

    out.push_str(BODY);
    out
}

/// The `SKILL.md` shipped in the Claude Code plugin (`plugin/`). It cannot list accounts,
/// choices or agents, because nothing regenerates it, so it points to `list_harnesses`
/// and `list_agents`. It carries no [`MARKER`]: `refresh` never touches it.
pub fn render_plugin_skill() -> String {
    let mut out = String::from(FRONT_MATTER);
    out.push_str("\n# superorchestrator\n\n");
    out.push_str(
        "Use the `superorchestrator` MCP tools to hand work to subagents that run on other \
         harnesses and accounts. This skill comes with the superorchestrator plugin.\n\n\
         ## Accounts, choices and agents\n\n\
         Call `list_harnesses` for the accounts and choices on this machine, and `list_agents` \
         for custom agents. Pass `agent: \"<name>\"` to `spawn_agent` to use one. \
         `superorchestrator account add` and `superorchestrator init` set accounts and choices \
         up.\n\n",
    );
    out.push_str(BODY);
    out
}

/// Collapses whitespace and cuts `s` to `max` characters.
fn one_line(s: &str, max: usize) -> String {
    let flat = s.split_whitespace().collect::<Vec<_>>().join(" ");
    if flat.chars().count() <= max {
        return flat;
    }
    let cut: String = flat.chars().take(max.saturating_sub(3)).collect();
    format!("{cut}...")
}

/// The `SKILL.md` paths under `home`: one for Claude Code and one for the shared agents dir.
pub fn skill_files(home: &Path) -> Vec<PathBuf> {
    [".claude", ".agents"]
        .iter()
        .map(|d| home.join(d).join("skills").join(NAME).join("SKILL.md"))
        .collect()
}

/// Renders the skill from what is on disk now: accounts, `choices` in `config.toml` and the
/// user's agents. Project agents depend on the working directory, so they are left out.
pub fn render_current(paths: &Paths) -> Result<String, String> {
    let accounts = AccountFile::list(paths).map_err(|e| e.to_string())?;
    let choices = Config::load(paths).map_err(|e| e.to_string())?.choices;
    let agents = discover_user(paths).agents;
    Ok(render_skill(&accounts, &choices, &agents))
}

/// What [`refresh`] did.
#[derive(Debug, Default, PartialEq, Eq)]
pub struct Refresh {
    /// Files that were rewritten.
    pub updated: Vec<PathBuf>,
    /// Why a file or the render failed. Callers report these as warnings.
    pub errors: Vec<String>,
}

/// Regenerates the installed skill files. A file is touched only when it exists, carries
/// [`MARKER`] and differs from the new text, so nothing happens before `install` ran and a
/// hand-written skill of the same name is never replaced. No backup is made: the file is
/// generated.
///
/// Setting `SUPERORCHESTRATOR_SKIP_SKILL_REFRESH` (to any non-empty value) turns this off, for
/// runs that use a throwaway config dir against a real `HOME`, such as `scripts/smoke.sh`.
pub fn refresh(paths: &Paths, home: &Path) -> Refresh {
    let mut out = Refresh::default();
    if std::env::var_os(SKIP_ENV).is_some_and(|v| !v.is_empty()) {
        return out;
    }
    let mut existing: Vec<(PathBuf, String)> = Vec::new();
    for p in skill_files(home) {
        if std::fs::symlink_metadata(&p).is_ok_and(|m| m.file_type().is_symlink()) {
            out.errors
                .push(format!("not updating {}: it is a symlink", p.display()));
            continue;
        }
        let Ok(text) = std::fs::read_to_string(&p) else {
            continue;
        };
        if text.lines().any(|l| l.trim_end() == MARKER) {
            existing.push((p, text));
        }
    }
    if existing.is_empty() {
        return out;
    }
    let new = match render_current(paths) {
        Ok(s) => s,
        Err(e) => {
            out.errors.push(format!("could not render the skill: {e}"));
            return out;
        }
    };
    for (p, old) in existing {
        if old == new {
            continue;
        }
        match write_replace(&p, &new) {
            Ok(()) => out.updated.push(p),
            Err(e) => out
                .errors
                .push(format!("could not update {}: {e}", p.display())),
        }
    }
    out
}

/// A temp file name next to `path`, unique per call (process id plus a counter), so
/// concurrent refreshes from the CLI, the supervisor and the web API never share one.
fn temp_path(path: &Path) -> PathBuf {
    static COUNTER: AtomicU64 = AtomicU64::new(0);
    let n = COUNTER.fetch_add(1, Ordering::Relaxed);
    path.with_file_name(format!(".SKILL.md.tmp.{}.{n}", std::process::id()))
}

/// Writes through a temp file in the same directory, keeping the file's mode.
fn write_replace(path: &Path, text: &str) -> std::io::Result<()> {
    use std::os::unix::fs::PermissionsExt;
    let mode = std::fs::metadata(path)?.permissions().mode() & 0o7777;
    let tmp = temp_path(path);
    let result = (|| {
        use std::io::Write;
        std::fs::OpenOptions::new()
            .write(true)
            .create_new(true)
            .open(&tmp)?
            .write_all(text.as_bytes())?;
        std::fs::set_permissions(&tmp, std::fs::Permissions::from_mode(mode))?;
        std::fs::rename(&tmp, path)
    })();
    if result.is_err() {
        let _ = std::fs::remove_file(&tmp);
    }
    result
}

const BODY: &str = "\
Call `list_harnesses` for the live picture: signed-in state, headroom and active runs per \
account.

## route or spawn_agent

- `route` previews which choice and account the router would pick. It runs nothing. Use it \
when you want to see or sanity-check a decision first.
- `spawn_agent` starts a run. With `harness: auto` (the default) the router picks. Pass \
`account`, `model` or `effort` only when you have a reason to override it. Set `wait: true` to \
block until the run finishes; otherwise it returns a run id.

## Writing a task brief

The subagent starts with no context. Put in the `prompt`:

1. The goal in one or two sentences.
2. Acceptance criteria: observable checks that say the work is done (tests that must pass, \
commands that must succeed).
3. Out of scope: what it must not touch or decide.
4. Pointers: files, docs and constraints it needs.

Use `output_schema` when you need a structured final result, and `review: true` when you want to \
inspect the work before it counts as done.

## Waiting, messaging and reviewing

- `wait_agent(runs, timeout)` returns when a listed run finishes, asks a question or reports \
progress, or when the timeout ends.
- `get_run` shows state, recent events, the final result and the worktree. Review a run's \
changes with `get_run(run, diff: true)` (stat and patch), not by reading its files.
- `send_message(run, text)` talks to a running run; sent to a finished run it resumes the \
session.
- `read_messages` returns unread messages for you. Answer a child's question with \
`send_message`.
- A run in `pending_review` waits for `accept_run` or `reject_run`. Land accepted work with \
`accept_run(run, merge: true)`: it merges the run's branch into the checkout it started from \
and removes the worktree. A refused or conflicting merge leaves the run at the gate with the \
reason; without `merge`, the result gives the branch and the command to merge it.
- `cancel_agent` stops a run and its subtree.

## If you are a subagent

You run with a run id and must never wait for a person.

- `report_progress(step, status)` at each step.
- `ask_parent(question, options?)` for decisions and blockers. It blocks until answered.
- `read_messages` for messages from your parent.
- Finish with a final result, matching the schema if one was given.
- Call `spawn_agent` only when your depth is below 2.

## Checking on things

Run `superorchestrator status` for accounts, headroom and the supervisor, and \
`superorchestrator runs list` for runs.
";

#[cfg(test)]
mod tests {
    use super::*;
    use crate::parse::{AgentSource, HarnessPref};
    use so_core::Harness;

    fn choice(id: &str, enabled: bool) -> Choice {
        Choice {
            id: id.into(),
            harness: Harness::Codex,
            model: "gpt".into(),
            effort: Some("high".into()),
            roles: vec!["code".into()],
            description: "fast".into(),
            enabled,
        }
    }

    fn agent(name: &str, description: &str) -> AgentDef {
        crate::parse_agent(
            &format!(
                "---\nname: {name}\ndescription: \"{description}\"\nharness: codex\n---\nbody\n"
            ),
            Path::new("/x/AGENT.md"),
            None,
            AgentSource::User,
            name,
        )
        .unwrap()
    }

    #[test]
    fn lists_accounts_and_enabled_choices_with_marker() {
        let mut off = AccountFile::new("claude-b", Harness::Claude, "~/b", "claude").unwrap();
        off.enabled = false;
        let accounts = [
            AccountFile::new("codex-a", Harness::Codex, "~/a", "codex").unwrap(),
            off,
        ];
        let s = render_skill(&accounts, &[choice("c1", true), choice("c2", false)], &[]);
        assert!(s.starts_with("---\nname: superorchestrator\n"));
        assert!(s.contains(MARKER));
        assert!(s.contains("- `codex-a`: codex, cap"));
        assert!(s.contains("(disabled)"));
        assert!(s.contains("`c1`: codex / gpt (high), roles: code. fast"));
        assert!(!s.contains("`c2`"));
        assert!(s.contains("superorchestrator status"));
    }

    #[test]
    fn empty_state_still_renders() {
        let s = render_skill(&[], &[], &[]);
        assert!(s.contains("No accounts are configured"));
        assert!(s.contains("No choices are enabled"));
        assert!(s.contains("No custom agents are defined"));
    }

    #[test]
    fn lists_agents_on_one_line_each() {
        let a = agent("pr-reviewer", "Reviews a PR.\nFinds bugs.");
        let s = render_skill(&[], &[], &[a]);
        assert!(s.contains("## Agents"));
        assert!(s.contains("Pass `agent: \"<name>\"`"));
        assert!(s.contains("- `pr-reviewer` (codex): Reviews a PR. Finds bugs.\n"));
        assert!(!s.contains("No custom agents"));
    }

    #[test]
    fn long_agent_descriptions_are_cut() {
        let long = "word ".repeat(100);
        let s = render_skill(&[], &[], &[agent("a", &long)]);
        let line = s.lines().find(|l| l.starts_with("- `a`")).unwrap();
        assert!(line.ends_with("..."));
        assert!(line.chars().count() < DESCRIPTION_MAX + 30);
        assert_eq!(HarnessPref::Auto.as_str(), "auto");
    }

    #[test]
    fn plugin_skill_has_no_marker_and_points_to_the_tools() {
        let s = render_plugin_skill();
        assert!(s.starts_with("---\nname: superorchestrator\n"));
        assert!(!s.contains(MARKER));
        assert!(s.contains("`list_harnesses`") && s.contains("## route or spawn_agent"));
    }

    struct Fixture {
        _dir: tempfile::TempDir,
        paths: Paths,
        home: PathBuf,
    }

    fn fixture() -> Fixture {
        let dir = tempfile::tempdir().unwrap();
        let paths = Paths::from_dir(dir.path().join("cfg"));
        std::fs::create_dir_all(&paths.config_dir).unwrap();
        let home = dir.path().join("home");
        std::fs::create_dir_all(&home).unwrap();
        Fixture {
            _dir: dir,
            paths,
            home,
        }
    }

    fn install_marked(f: &Fixture) {
        for p in skill_files(&f.home) {
            std::fs::create_dir_all(p.parent().unwrap()).unwrap();
            std::fs::write(&p, format!("old\n{MARKER}\n")).unwrap();
        }
    }

    #[test]
    fn refresh_does_nothing_when_the_skill_is_not_installed() {
        let f = fixture();
        let r = refresh(&f.paths, &f.home);
        assert_eq!(r, Refresh::default());
        assert!(!f.home.join(".claude").exists());
    }

    #[test]
    fn refresh_rewrites_marked_files_and_then_settles() {
        let f = fixture();
        install_marked(&f);
        AccountFile::new("codex-a", Harness::Codex, "~/a", "codex")
            .unwrap()
            .save(&f.paths)
            .unwrap();
        let r = refresh(&f.paths, &f.home);
        assert_eq!(r.updated.len(), 2, "{r:?}");
        assert!(r.errors.is_empty());
        for p in skill_files(&f.home) {
            let s = std::fs::read_to_string(p).unwrap();
            assert!(s.contains("`codex-a`") && s.contains(MARKER));
        }
        // Nothing changed since, so nothing is written.
        assert!(refresh(&f.paths, &f.home).updated.is_empty());
    }

    #[test]
    fn refresh_follows_account_and_agent_changes() {
        let f = fixture();
        install_marked(&f);
        refresh(&f.paths, &f.home);
        let dir = f.paths.agents_dir().join("helper");
        std::fs::create_dir_all(&dir).unwrap();
        std::fs::write(
            dir.join("AGENT.md"),
            "---\nname: helper\ndescription: Helps.\n---\nbody\n",
        )
        .unwrap();
        let r = refresh(&f.paths, &f.home);
        assert_eq!(r.updated.len(), 2);
        let s = std::fs::read_to_string(&skill_files(&f.home)[0]).unwrap();
        assert!(s.contains("- `helper` (auto): Helps."));
    }

    #[test]
    fn refresh_leaves_a_file_without_the_marker_alone() {
        let f = fixture();
        let p = &skill_files(&f.home)[0];
        std::fs::create_dir_all(p.parent().unwrap()).unwrap();
        std::fs::write(p, "mine").unwrap();
        let r = refresh(&f.paths, &f.home);
        assert_eq!(r, Refresh::default());
        assert_eq!(std::fs::read_to_string(p).unwrap(), "mine");
    }

    #[test]
    fn the_marker_must_be_a_whole_line() {
        let f = fixture();
        let p = &skill_files(&f.home)[0];
        std::fs::create_dir_all(p.parent().unwrap()).unwrap();
        let mine = format!("notes that mention {MARKER} in a sentence\n");
        std::fs::write(p, &mine).unwrap();
        assert_eq!(refresh(&f.paths, &f.home), Refresh::default());
        assert_eq!(std::fs::read_to_string(p).unwrap(), mine);
    }

    #[test]
    fn a_symlinked_skill_is_skipped_with_a_warning() {
        let f = fixture();
        let real = f.home.join("elsewhere.md");
        std::fs::write(&real, format!("old\n{MARKER}\n")).unwrap();
        let p = &skill_files(&f.home)[0];
        std::fs::create_dir_all(p.parent().unwrap()).unwrap();
        std::os::unix::fs::symlink(&real, p).unwrap();
        let r = refresh(&f.paths, &f.home);
        assert!(r.updated.is_empty());
        assert_eq!(r.errors.len(), 1, "{r:?}");
        assert!(r.errors[0].contains("symlink"));
        assert!(std::fs::read_to_string(&real).unwrap().starts_with("old"));
    }

    #[test]
    fn temp_names_are_unique_per_call() {
        let p = Path::new("/h/.claude/skills/superorchestrator/SKILL.md");
        assert_ne!(temp_path(p), temp_path(p));
    }

    #[test]
    fn refresh_reports_a_broken_config_and_keeps_the_files() {
        let f = fixture();
        install_marked(&f);
        std::fs::write(f.paths.config_toml(), "this is = = not toml").unwrap();
        let r = refresh(&f.paths, &f.home);
        assert!(r.updated.is_empty());
        assert_eq!(r.errors.len(), 1);
        let s = std::fs::read_to_string(&skill_files(&f.home)[0]).unwrap();
        assert!(s.starts_with("old"));
    }
}
