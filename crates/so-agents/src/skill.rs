//! The shipped skills (SPEC 19.1): `use-superorchestrator-mcp`, generated from the current
//! accounts, choices and agents and regenerated whenever they change, and the static
//! `superorchestrator-cli`.
//!
//! They live in this crate so the CLI and the web API can both refresh them.

use std::fmt::Write as _;
use std::path::{Path, PathBuf};

use so_core::{AccountFile, Choice, Config, Paths};

use crate::{AgentDef, discover::discover_user};

/// Directory name of the MCP skill under `~/.claude/skills` and `~/.agents/skills`.
pub const MCP_NAME: &str = "use-superorchestrator-mcp";

/// Directory name of the CLI skill.
pub const CLI_NAME: &str = "superorchestrator-cli";

/// Directory name of the single skill that earlier versions shipped. `install` removes it
/// when its `SKILL.md` carries [`MARKER`].
pub const OLD_NAME: &str = "superorchestrator";

const MCP_FRONT_MATTER: &str = "---\nname: use-superorchestrator-mcp\ndescription: Delegate coding \
work to agents on other harnesses and accounts via superorchestrator MCP tools: route, spawn, \
wait, review.\n---\n";

const CLI_FRONT_MATTER: &str = "---\nname: superorchestrator-cli\ndescription: Use the \
superorchestrator command line: manage accounts (add, sign in, enable, disable), check status \
and headroom, list, watch and join runs from a shell.\n---\n";

/// Environment variable that disables [`refresh`].
pub const SKIP_ENV: &str = "SUPERORCHESTRATOR_SKIP_SKILL_REFRESH";

/// Longest agent description kept in the skill, in characters.
const DESCRIPTION_MAX: usize = 160;

/// Marker line in every generated `SKILL.md`. `uninstall` and re-generation only touch
/// files that carry it.
pub const MARKER: &str = "<!-- superorchestrator:managed -->";

/// Renders the skill's `SKILL.md`.
pub fn render_skill(accounts: &[AccountFile], choices: &[Choice], agents: &[AgentDef]) -> String {
    let mut out = String::new();
    out.push_str(MCP_FRONT_MATTER);
    let _ = writeln!(out, "{MARKER}\n");
    out.push_str(WORKFLOW);
    out.push_str("Generated by `superorchestrator install`; do not edit.\n\n");

    out.push_str("## Accounts\n\n");
    if accounts.is_empty() {
        out.push_str("None. Run `superorchestrator account add`.\n\n");
    } else {
        for a in accounts {
            let _ = writeln!(
                out,
                "- `{}`: {}, cap {}{}",
                a.name,
                a.harness.as_str(),
                a.cap,
                if a.enabled { "" } else { " (disabled)" }
            );
        }
        out.push('\n');
    }

    out.push_str("## Choices\n\n");
    let enabled: Vec<&Choice> = choices.iter().filter(|c| c.enabled).collect();
    if enabled.is_empty() {
        out.push_str("None enabled. Edit `choices` in `config.toml`.\n\n");
    } else {
        for c in enabled {
            let _ = write!(out, "- `{}`: {} / {}", c.id, c.harness.as_str(), c.model);
            if let Some(e) = &c.effort {
                let _ = write!(out, " ({e})");
            }
            if c.model.ends_with("-free") || c.model.ends_with(":free") {
                out.push_str(" free");
            }
            if !c.roles.is_empty() && c.roles != ["worker"] {
                let _ = write!(out, ", roles: {}", c.roles.join(", "));
            }
            if !c.description.is_empty() {
                let _ = write!(out, ". {}", c.description);
            }
            out.push('\n');
        }
        out.push('\n');
    }

    out.push_str("## Agents\n\n");
    if agents.is_empty() {
        out.push_str("None. `superorchestrator agent create` makes one.\n\n");
    } else {
        out.push_str("Pass `agent: \"<name>\"` to `spawn_agent`.\n\n");
        for a in agents {
            let _ = write!(out, "- `{}` ({})", a.name, a.harness.as_str());
            let d = one_line(&a.description, DESCRIPTION_MAX);
            if !d.is_empty() {
                let _ = write!(out, ": {d}");
            }
            out.push('\n');
        }
        out.push('\n');
    }

    out.push_str(BODY);
    out
}

/// The `SKILL.md` for the CLI skill, with [`MARKER`]. Static text.
pub fn render_cli_skill() -> String {
    let mut out = String::from(CLI_FRONT_MATTER);
    let _ = writeln!(out, "{MARKER}\n");
    out.push_str(CLI_BODY);
    out
}

/// The CLI skill shipped in the Claude Code plugin (`plugin/`): [`render_cli_skill`] without
/// [`MARKER`], so `refresh` never touches it.
pub fn render_plugin_cli_skill() -> String {
    let mut out = String::from(CLI_FRONT_MATTER);
    out.push('\n');
    out.push_str(CLI_BODY);
    out
}

/// The MCP skill shipped in the Claude Code plugin (`plugin/`). It cannot list accounts,
/// choices or agents, because nothing regenerates it, so it points to `list_harnesses`
/// and `list_agents`. It carries no [`MARKER`]: `refresh` never touches it.
pub fn render_plugin_mcp_skill() -> String {
    let mut out = String::from(MCP_FRONT_MATTER);
    out.push('\n');
    out.push_str(WORKFLOW);
    out.push_str(
        "Accounts, choices: `list_harnesses`. Agents: `list_agents`, then `agent: \"<name>\"`.\n\n",
    );
    out.push_str(BODY);
    out
}

/// Collapses whitespace and cuts `s` to `max` characters.
fn one_line(s: &str, max: usize) -> String {
    let flat = s.split_whitespace().collect::<Vec<_>>().join(" ");
    if flat.chars().count() <= max {
        return flat;
    }
    let cut: String = flat.chars().take(max.saturating_sub(3)).collect();
    format!("{cut}...")
}

fn files_for(home: &Path, name: &str) -> Vec<PathBuf> {
    [".claude", ".agents"]
        .iter()
        .map(|d| home.join(d).join("skills").join(name).join("SKILL.md"))
        .collect()
}

/// The MCP skill's `SKILL.md` paths under `home`: one for Claude Code and one for the
/// shared agents dir.
pub fn skill_files(home: &Path) -> Vec<PathBuf> {
    files_for(home, MCP_NAME)
}

/// The CLI skill's `SKILL.md` paths under `home`.
pub fn cli_skill_files(home: &Path) -> Vec<PathBuf> {
    files_for(home, CLI_NAME)
}

/// The old single skill's `SKILL.md` paths under `home`.
pub fn old_skill_files(home: &Path) -> Vec<PathBuf> {
    files_for(home, OLD_NAME)
}

/// True when `text` carries [`MARKER`] on a line of its own.
pub fn is_managed(text: &str) -> bool {
    text.lines().any(|l| l.trim_end() == MARKER)
}

/// Renders the skill from what is on disk now: accounts, `choices` in `config.toml` and the
/// user's agents. Project agents depend on the working directory, so they are left out.
pub fn render_current(paths: &Paths) -> Result<String, String> {
    let accounts = AccountFile::list(paths).map_err(|e| e.to_string())?;
    let choices = Config::load(paths).map_err(|e| e.to_string())?.choices;
    let agents = discover_user(paths).agents;
    Ok(render_skill(&accounts, &choices, &agents))
}

/// What [`refresh`] did.
#[derive(Debug, Default, PartialEq, Eq)]
pub struct Refresh {
    /// Files that were rewritten.
    pub updated: Vec<PathBuf>,
    /// Why a file or the render failed. Callers report these as warnings.
    pub errors: Vec<String>,
}

/// Regenerates the installed skills. The MCP skill is rewritten only when it exists, carries
/// [`MARKER`] and differs from the new text, so nothing happens before `install` ran and a
/// hand-written skill of the same name is never replaced. Next to a managed MCP skill, the
/// CLI skill is written when missing and brought up to date when it carries [`MARKER`]. No
/// backup is made: the files are generated.
///
/// Setting `SUPERORCHESTRATOR_SKIP_SKILL_REFRESH` (to any non-empty value) turns this off, for
/// runs that use a throwaway config dir against a real `HOME`, such as `scripts/smoke.sh`.
pub fn refresh(paths: &Paths, home: &Path) -> Refresh {
    let mut out = Refresh::default();
    if std::env::var_os(SKIP_ENV).is_some_and(|v| !v.is_empty()) {
        return out;
    }
    let mut existing: Vec<(PathBuf, String, PathBuf)> = Vec::new();
    for (p, cli) in skill_files(home).into_iter().zip(cli_skill_files(home)) {
        if is_symlink(&p) {
            out.errors
                .push(format!("not updating {}: it is a symlink", p.display()));
            continue;
        }
        let Ok(text) = std::fs::read_to_string(&p) else {
            continue;
        };
        if is_managed(&text) {
            existing.push((p, text, cli));
        }
    }
    if existing.is_empty() {
        return out;
    }
    let new = match render_current(paths) {
        Ok(s) => s,
        Err(e) => {
            out.errors.push(format!("could not render the skill: {e}"));
            return out;
        }
    };
    let cli_new = render_cli_skill();
    for (p, old, cli) in existing {
        if old != new {
            sync(&mut out, &p, &new);
        }
        if is_symlink(&cli) {
            out.errors
                .push(format!("not updating {}: it is a symlink", cli.display()));
            continue;
        }
        match std::fs::read_to_string(&cli) {
            Ok(text) if !is_managed(&text) || text == cli_new => {}
            Ok(_) => sync(&mut out, &cli, &cli_new),
            Err(e) if e.kind() == std::io::ErrorKind::NotFound => {
                sync(&mut out, &cli, &cli_new);
            }
            Err(e) => out
                .errors
                .push(format!("could not read {}: {e}", cli.display())),
        }
    }
    out
}

fn is_symlink(p: &Path) -> bool {
    std::fs::symlink_metadata(p).is_ok_and(|m| m.file_type().is_symlink())
}

fn sync(out: &mut Refresh, path: &Path, text: &str) {
    match write_replace(path, text) {
        Ok(()) => out.updated.push(path.to_path_buf()),
        Err(e) => out
            .errors
            .push(format!("could not update {}: {e}", path.display())),
    }
}

/// Writes through [`so_core::fsutil::write_file_atomic`].
fn write_replace(path: &Path, text: &str) -> std::io::Result<()> {
    so_core::fsutil::write_file_atomic(path, text.as_bytes())
}

