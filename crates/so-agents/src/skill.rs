pub const MCP_NAME: &str = "use-superorchestrator-mcp";

/// Directory name of the CLI skill.
pub const CLI_NAME: &str = "superorchestrator-cli";

/// Directory name of the configuration skill.
pub const CONFIG_NAME: &str = "superorchestrator-config";

/// Directory name of the single skill that earlier versions shipped. `install` removes it
/// when its `SKILL.md` carries [`MARKER`].
pub const OLD_NAME: &str = "superorchestrator";

const MCP_FRONT_MATTER: &str = r#"---
name: use-superorchestrator-mcp
description: "Delegate coding work to agents on other harnesses and accounts via superorchestrator MCP tools: route, spawn, wait, review."
---
"#;

const CLI_FRONT_MATTER: &str = "---\nname: superorchestrator-cli\ndescription: Drive the superorchestrator CLI for accounts, levels, config, models, agent profiles, workflows and runs.\n---\n";

const CONFIG_FRONT_MATTER: &str = "---\nname: superorchestrator-config\ndescription: Configure superorchestrator workflows, accounts, agent profiles, routing and levels.\n---\n";

/// Environment variable that disables [`refresh`].
pub const SKIP_ENV: &str = "SUPERORCHESTRATOR_SKIP_SKILL_REFRESH";

/// Longest agent description kept in the skill, in characters.
const DESCRIPTION_MAX: usize = 160;

/// Marker line in every generated `SKILL.md`. `uninstall` and re-generation only touch
/// files that carry it.
pub const MARKER: &str = "<!-- superorchestrator:managed -->";

/// Renders the skill's `SKILL.md`.
pub fn render_skill(accounts: &[AccountFile], levels: &[Level], agents: &[AgentDef]) -> String {
    let mut out = String::new();
    out.push_str(MCP_FRONT_MATTER);
    let _ = writeln!(out, "{MARKER}\n");
    out.push_str(WORKFLOW);
    out.push_str("Generated by `superorchestrator install`; do not edit.\n\n");

    out.push_str("## Accounts\n\n");
    if accounts.is_empty() {
        out.push_str("None. Run `superorchestrator account add`.\n\n");
    } else {
        for a in accounts {
            let _ = writeln!(
                out,
                "- `{}`: {}, cap {}{}",
                a.name,
                a.harness.as_str(),
                a.cap,
                if a.enabled { "" } else { " (disabled)" }
            );
        }
        out.push('\n');
    }

    out.push_str("## Levels\n\n");
    if levels.iter().all(|l| l.models.is_empty()) {
        out.push_str("None. List models on `[[router.levels]]` in `config.toml`.\n\n");
    } else {
        for l in levels.iter().filter(|l| !l.models.is_empty()) {
            let refs: Vec<String> = l
                .models
                .iter()
                .map(|m| {
                    let free = if so_core::model_name_is_free(&m.model) {
                        " free"
                    } else {
                        ""
                    };
                    format!("`{}`{free}", m.id())
                })
                .collect();
            let _ = writeln!(
                out,
                "- {} ({}-{}): {}",
                l.name,
                l.min,
                l.max,
                refs.join(", ")
            );
        }
        out.push('\n');
    }

    out.push_str("## Agents\n\n");
    if agents.is_empty() {
        out.push_str("None. `superorchestrator agent create` makes one.\n\n");
    } else {
        out.push_str("Pass `agent: \"<name>\"` to `spawn_agent`.\n\n");
        for a in agents {
            let _ = write!(out, "- `{}` ({})", a.name, a.harness.as_str());
            let d = one_line(&a.description, DESCRIPTION_MAX);
            if !d.is_empty() {
                let _ = write!(out, ": {d}");
            }
            out.push('\n');
        }
        out.push('\n');
    }

    out.push_str(BODY);
    out
}

/// The `SKILL.md` for the CLI skill, with [`MARKER`]. Static text.
pub fn render_cli_skill() -> String {
    let mut out = String::from(CLI_FRONT_MATTER);
    let _ = writeln!(out, "{MARKER}\n");
    out.push_str(CLI_BODY);
    out
}

/// The configuration skill installed alongside the CLI and MCP skills.
pub fn render_config_skill() -> String {
    format!("{CONFIG_FRONT_MATTER}{MARKER}\n\n{CONFIG_BODY}")
}

/// The plugin copy of the configuration skill, without the managed marker.
